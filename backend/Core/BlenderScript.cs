    public static class BlenderScript
    {
        public static string BuildBlenderSimulationScript(string imageFileName, string heightmapFileName, double widthMm, double heightMm, double backingMm, double totalThicknessMm, double baseThicknessMm, double viewingAngleDeg, int viewCount, bool vertical, double refractiveIndex, bool lensFree)
        {
            var sb = new StringBuilder();
            string imageLiteral = imageFileName.Replace("\\", "\\\\");
            string heightLiteral = heightmapFileName.Replace("\\", "\\\\");
            sb.AppendLine("import bpy, os, math, sys");
            sb.AppendLine("from mathutils import Matrix");
            sb.AppendLine();
            sb.AppendLine("expected_image_name = r\"" + imageLiteral + "\"");
            sb.AppendLine("expected_heightmap_name = r\"" + heightLiteral + "\"");
            sb.AppendLine();
            sb.AppendLine("def _candidate_dir(path):");
            sb.AppendLine("    if not path:");
            sb.AppendLine("        return None");
            sb.AppendLine("    try:");
            sb.AppendLine("        if path.startswith('//'):");
            sb.AppendLine("            path = bpy.path.abspath(path)");
            sb.AppendLine("        path = os.path.abspath(path)");
            sb.AppendLine("        if os.path.isfile(path):");
            sb.AppendLine("            path = os.path.dirname(path)");
            sb.AppendLine("        return path");
            sb.AppendLine("    except Exception:");
            sb.AppendLine("        return None");
            sb.AppendLine();
            sb.AppendLine("def find_package_dir():");
            sb.AppendLine("    candidates = []");
            sb.AppendLine("    env_dir = os.environ.get('LENTICULAR_SIM_DIR', '')");
            sb.AppendLine("    if env_dir:");
            sb.AppendLine("        candidates.append(_candidate_dir(env_dir))");
            sb.AppendLine("    try:");
            sb.AppendLine("        if '__file__' in globals():");
            sb.AppendLine("            candidates.append(_candidate_dir(__file__))");
            sb.AppendLine("    except Exception:");
            sb.AppendLine("        pass");
            sb.AppendLine("    try:");
            sb.AppendLine("        for text in bpy.data.texts:");
            sb.AppendLine("            filepath = getattr(text, 'filepath', '')");
            sb.AppendLine("            if filepath:");
            sb.AppendLine("                resolved = bpy.path.abspath(filepath) if filepath.startswith('//') else filepath");
            sb.AppendLine("                if os.path.basename(resolved).lower() == 'blender_simulation.py':");
            sb.AppendLine("                    candidates.append(_candidate_dir(resolved))");
            sb.AppendLine("        for text in bpy.data.texts:");
            sb.AppendLine("            filepath = getattr(text, 'filepath', '')");
            sb.AppendLine("            if filepath:");
            sb.AppendLine("                resolved = bpy.path.abspath(filepath) if filepath.startswith('//') else filepath");
            sb.AppendLine("                candidates.append(_candidate_dir(resolved))");
            sb.AppendLine("    except Exception:");
            sb.AppendLine("        pass");
            sb.AppendLine("    if bpy.data.filepath:");
            sb.AppendLine("        candidates.append(_candidate_dir(bpy.data.filepath))");
            sb.AppendLine("    candidates.append(_candidate_dir(os.getcwd()))");
            sb.AppendLine("    seen = set()");
            sb.AppendLine("    for candidate in candidates:");
            sb.AppendLine("        if not candidate:");
            sb.AppendLine("            continue");
            sb.AppendLine("        key = os.path.normcase(os.path.normpath(candidate))");
            sb.AppendLine("        if key in seen:");
            sb.AppendLine("            continue");
            sb.AppendLine("        seen.add(key)");
            sb.AppendLine("        if os.path.isfile(os.path.join(candidate, expected_image_name)) and os.path.isfile(os.path.join(candidate, expected_heightmap_name)):");
            sb.AppendLine("            return candidate");
            sb.AppendLine("    checked = '\\n'.join(sorted(seen)) if seen else '(no usable folders found)'");
            sb.AppendLine("    raise RuntimeError('Could not locate the extracted Blender simulation package. Make sure the ZIP is fully extracted and blender_simulation.py, ' + expected_image_name + ', and ' + expected_heightmap_name + ' are in the same folder.\\n\\nFolders checked:\\n' + checked)");
            sb.AppendLine();
            sb.AppendLine("base_dir = find_package_dir()");
            sb.AppendLine("image_path = os.path.join(base_dir, expected_image_name)");
            sb.AppendLine("heightmap_path = os.path.join(base_dir, expected_heightmap_name)");
            sb.AppendLine("print('Lenticular simulation package:', base_dir)");
            sb.AppendLine("width_m = " + (widthMm / 1000.0).ToString("0.########", CultureInfo.InvariantCulture));
            sb.AppendLine("height_m = " + (heightMm / 1000.0).ToString("0.########", CultureInfo.InvariantCulture));
            sb.AppendLine("backing_m = " + (backingMm / 1000.0).ToString("0.########", CultureInfo.InvariantCulture));
            sb.AppendLine("peak_m = " + (totalThicknessMm / 1000.0).ToString("0.########", CultureInfo.InvariantCulture));
            sb.AppendLine("valley_m = " + (baseThicknessMm / 1000.0).ToString("0.########", CultureInfo.InvariantCulture));
            sb.AppendLine("view_angle_deg = " + viewingAngleDeg.ToString("0.########", CultureInfo.InvariantCulture));
            sb.AppendLine("view_count = " + Math.Max(1, viewCount).ToString(CultureInfo.InvariantCulture));
            sb.AppendLine("vertical_lenses = " + (vertical ? "True" : "False"));
            sb.AppendLine("ior_value = " + refractiveIndex.ToString("0.###", CultureInfo.InvariantCulture));
            sb.AppendLine("lens_free = " + (lensFree ? "True" : "False"));
            sb.AppendLine();
            sb.AppendLine("def clear_generated_scene():");
            sb.AppendLine("    generated_exact = {'Backing', 'InterlacedImage', 'LenticularLens', 'DirectionalRelief', 'ViewTarget', 'PrintRoot'}");
            sb.AppendLine("    for obj in list(bpy.data.objects):");
            sb.AppendLine("        if obj.name.startswith('LT_') or obj.name.startswith('View_') or obj.name in generated_exact:");
            sb.AppendLine("            bpy.data.objects.remove(obj, do_unlink=True)");
            sb.AppendLine("    for block in list(bpy.data.meshes):");
            sb.AppendLine("        if block.users == 0:");
            sb.AppendLine("            bpy.data.meshes.remove(block)");
            sb.AppendLine();
            sb.AppendLine("def load_axis_values(path, vertical):");
            sb.AppendLine("    img = bpy.data.images.load(path, check_existing=True)");
            sb.AppendLine("    img.colorspace_settings.name = 'Non-Color'");
            sb.AppendLine("    width, height = img.size[0], img.size[1]");
            sb.AppendLine("    pixels = list(img.pixels[:])");
            sb.AppendLine("    values = []");
            sb.AppendLine("    if vertical:");
            sb.AppendLine("        y = max(0, min(height - 1, height // 2))");
            sb.AppendLine("        for x in range(width):");
            sb.AppendLine("            idx = (y * width + x) * 4");
            sb.AppendLine("            values.append(max(0.0, min(1.0, pixels[idx])))");
            sb.AppendLine("    else:");
            sb.AppendLine("        x = max(0, min(width - 1, width // 2))");
            sb.AppendLine("        for y in range(height):");
            sb.AppendLine("            idx = (y * width + x) * 4");
            sb.AppendLine("            values.append(max(0.0, min(1.0, pixels[idx])))");
            sb.AppendLine("    return img, values");
            sb.AppendLine();
            sb.AppendLine("def build_lens_mesh(values, width_m, height_m, peak_m, vertical):");
            sb.AppendLine("    n = max(2, len(values))");
            sb.AppendLine("    verts = []");
            sb.AppendLine("    faces = []");
            sb.AppendLine("    if vertical:");
            sb.AppendLine("        for i, v in enumerate(values):");
            sb.AppendLine("            x = -width_m / 2.0 + (width_m * i / (n - 1))");
            sb.AppendLine("            z = v * peak_m");
            sb.AppendLine("            verts.extend([(x, -height_m / 2.0, z), (x, height_m / 2.0, z), (x, -height_m / 2.0, 0.0), (x, height_m / 2.0, 0.0)])");
            sb.AppendLine("    else:");
            sb.AppendLine("        for i, v in enumerate(values):");
            sb.AppendLine("            y = -height_m / 2.0 + (height_m * i / (n - 1))");
            sb.AppendLine("            z = v * peak_m");
            sb.AppendLine("            verts.extend([(-width_m / 2.0, y, z), (width_m / 2.0, y, z), (-width_m / 2.0, y, 0.0), (width_m / 2.0, y, 0.0)])");
            sb.AppendLine("    for i in range(n - 1):");
            sb.AppendLine("        a = i * 4");
            sb.AppendLine("        b = (i + 1) * 4");
            sb.AppendLine("        faces.append((a, b, b + 1, a + 1))");
            sb.AppendLine("        faces.append((a + 2, a + 3, b + 3, b + 2))");
            sb.AppendLine("        faces.append((a, a + 2, b + 2, b))");
            sb.AppendLine("        faces.append((a + 1, b + 1, b + 3, a + 3))");
            sb.AppendLine("    faces.append((0, 1, 3, 2))");
            sb.AppendLine("    end = (n - 1) * 4");
            sb.AppendLine("    faces.append((end, end + 2, end + 3, end + 1))");
            sb.AppendLine("    mesh = bpy.data.meshes.new('LenticularLens')");
            sb.AppendLine("    mesh.from_pydata(verts, [], faces)");
            sb.AppendLine("    mesh.update()");
            sb.AppendLine("    obj = bpy.data.objects.new('LenticularLens', mesh)");
            sb.AppendLine("    bpy.context.collection.objects.link(obj)");
            sb.AppendLine("    bpy.context.view_layer.objects.active = obj");
            sb.AppendLine("    obj.select_set(True)");
            sb.AppendLine("    bpy.ops.object.shade_smooth()");
            sb.AppendLine("    return obj");
            sb.AppendLine();
            sb.AppendLine("def apply_planar_uv(obj):");
            sb.AppendLine("    mesh = obj.data");
            sb.AppendLine("    uv = mesh.uv_layers.get('UVMap') or mesh.uv_layers.new(name='UVMap')");
            sb.AppendLine("    for poly in mesh.polygons:");
            sb.AppendLine("        for li in poly.loop_indices:");
            sb.AppendLine("            vi = mesh.loops[li].vertex_index");
            sb.AppendLine("            co = mesh.vertices[vi].co");
            sb.AppendLine("            u = (co.x + width_m / 2.0) / max(width_m, 1e-12)");
            sb.AppendLine("            v = (co.y + height_m / 2.0) / max(height_m, 1e-12)");
            sb.AppendLine("            uv.data[li].uv = (max(0.0, min(1.0, u)), max(0.0, min(1.0, v)))");
            sb.AppendLine();
            sb.AppendLine("def make_diffuse_material(name, color):");
            sb.AppendLine("    mat = bpy.data.materials.new(name)");
            sb.AppendLine("    mat.use_nodes = True");
            sb.AppendLine("    nt = mat.node_tree");
            sb.AppendLine("    nodes = nt.nodes");
            sb.AppendLine("    links = nt.links");
            sb.AppendLine("    output = nodes.get('Material Output')");
            sb.AppendLine("    for node in list(nodes):");
            sb.AppendLine("        if node != output:");
            sb.AppendLine("            nodes.remove(node)");
            sb.AppendLine("    diffuse = nodes.new('ShaderNodeBsdfDiffuse')");
            sb.AppendLine("    diffuse.name = 'Diffuse BSDF'");
            sb.AppendLine("    diffuse.label = 'Diffuse BSDF'");
            sb.AppendLine("    diffuse.inputs['Color'].default_value = color");
            sb.AppendLine("    if 'Roughness' in diffuse.inputs:");
            sb.AppendLine("        diffuse.inputs['Roughness'].default_value = 0.0");
            sb.AppendLine("    links.new(diffuse.outputs['BSDF'], output.inputs['Surface'])");
            sb.AppendLine("    return mat");
            sb.AppendLine();
            sb.AppendLine("def make_emission_material(name, image, strength):");
            sb.AppendLine("    mat = bpy.data.materials.new(name)");
            sb.AppendLine("    mat.use_nodes = True");
            sb.AppendLine("    nt = mat.node_tree");
            sb.AppendLine("    nodes = nt.nodes");
            sb.AppendLine("    links = nt.links");
            sb.AppendLine("    output = nodes.get('Material Output')");
            sb.AppendLine("    for node in list(nodes):");
            sb.AppendLine("        if node != output:");
            sb.AppendLine("            nodes.remove(node)");
            sb.AppendLine("    tex = nodes.new('ShaderNodeTexImage')");
            sb.AppendLine("    tex.image = image");
            sb.AppendLine("    emission = nodes.new('ShaderNodeEmission')");
            sb.AppendLine("    emission.name = 'Emission'");
            sb.AppendLine("    emission.label = 'Emission'");
            sb.AppendLine("    emission.inputs['Strength'].default_value = strength");
            sb.AppendLine("    links.new(tex.outputs['Color'], emission.inputs['Color'])");
            sb.AppendLine("    links.new(emission.outputs['Emission'], output.inputs['Surface'])");
            sb.AppendLine("    return mat");
            sb.AppendLine();
            sb.AppendLine("def make_refraction_material(name, color, roughness, ior):");
            sb.AppendLine("    mat = bpy.data.materials.new(name)");
            sb.AppendLine("    mat.use_nodes = True");
            sb.AppendLine("    nt = mat.node_tree");
            sb.AppendLine("    nodes = nt.nodes");
            sb.AppendLine("    links = nt.links");
            sb.AppendLine("    output = nodes.get('Material Output')");
            sb.AppendLine("    for node in list(nodes):");
            sb.AppendLine("        if node != output:");
            sb.AppendLine("            nodes.remove(node)");
            sb.AppendLine("    refraction = nodes.new('ShaderNodeBsdfRefraction')");
            sb.AppendLine("    refraction.name = 'Refraction BSDF'");
            sb.AppendLine("    refraction.label = 'Refraction BSDF'");
            sb.AppendLine("    refraction.inputs['Color'].default_value = color");
            sb.AppendLine("    refraction.inputs['Roughness'].default_value = roughness");
            sb.AppendLine("    refraction.inputs['IOR'].default_value = ior");
            sb.AppendLine("    links.new(refraction.outputs['BSDF'], output.inputs['Surface'])");
            sb.AppendLine("    return mat");
            sb.AppendLine();
            sb.AppendLine("def make_materials(interlaced_img):");
            sb.AppendLine("    substrate_mat = make_diffuse_material('Substrate', (0.92, 0.92, 0.92, 1.0))");
            sb.AppendLine("    print_mat = make_emission_material('InterlacedPrint', interlaced_img, 1.0)");
            sb.AppendLine("    lens_mat = make_refraction_material('ClearLens', (1.0, 1.0, 1.0, 1.0), 0.0, ior_value)");
            sb.AppendLine("    return substrate_mat, print_mat, lens_mat");
            sb.AppendLine();
            sb.AppendLine("def add_camera(angle_deg, distance_m, target, make_active, name):");
            sb.AppendLine("    lateral = math.sin(math.radians(angle_deg)) * distance_m");
            sb.AppendLine("    depth = math.cos(math.radians(angle_deg)) * distance_m + peak_m * 0.5");
            sb.AppendLine("    location = (lateral, depth, 0.0) if vertical_lenses else (0.0, depth, lateral)");
            sb.AppendLine("    bpy.ops.object.camera_add(location=location)");
            sb.AppendLine("    cam = bpy.context.active_object");
            sb.AppendLine("    cam.name = name");
            sb.AppendLine("    constraint = cam.constraints.new(type='TRACK_TO')");
            sb.AppendLine("    constraint.target = target");
            sb.AppendLine("    constraint.track_axis = 'TRACK_NEGATIVE_Z'");
            sb.AppendLine("    constraint.up_axis = 'UP_Y'");
            sb.AppendLine("    if make_active:");
            sb.AppendLine("        bpy.context.scene.camera = cam");
            sb.AppendLine("    return cam");
            sb.AppendLine();
            sb.AppendLine("clear_generated_scene()");
            sb.AppendLine("scene = bpy.context.scene");
            sb.AppendLine("scene.render.engine = 'CYCLES'");
            sb.AppendLine("scene.cycles.samples = 128");
            sb.AppendLine("scene.cycles.caustics_reflective = False");
            sb.AppendLine("scene.cycles.caustics_refractive = False");
            sb.AppendLine("scene.render.resolution_x = 1600");
            sb.AppendLine("scene.render.resolution_y = 1200");
            sb.AppendLine("scene.unit_settings.system = 'METRIC'");
            sb.AppendLine("scene.unit_settings.length_unit = 'MILLIMETERS'");
            sb.AppendLine("scene.unit_settings.scale_length = 1.0");
            sb.AppendLine("scene.world.use_nodes = True");
            sb.AppendLine("bg = scene.world.node_tree.nodes.get('Background')");
            sb.AppendLine("bg.inputs[0].default_value = (0.03, 0.03, 0.03, 1.0)");
            sb.AppendLine("bg.inputs[1].default_value = 0.05");
            sb.AppendLine();
            sb.AppendLine("interlaced_img = bpy.data.images.load(image_path, check_existing=True)");
            sb.AppendLine("_, axis_values = load_axis_values(heightmap_path, vertical_lenses)");
            sb.AppendLine("substrate_mat, print_mat, lens_mat = make_materials(interlaced_img)");
            sb.AppendLine();
            sb.AppendLine("bpy.ops.object.empty_add(type='PLAIN_AXES', location=(0.0, 0.0, 0.0))");
            sb.AppendLine("print_root = bpy.context.active_object");
            sb.AppendLine("print_root.name = 'LT_PrintRoot'");
            sb.AppendLine("print_root.rotation_mode = 'XYZ'");
            sb.AppendLine("print_root.rotation_euler[0] = -math.pi / 2.0");
            sb.AppendLine("print_root.rotation_euler[1] = math.pi");
            sb.AppendLine("print_root.rotation_euler[2] = 0.0");
            sb.AppendLine("bpy.context.view_layer.update()");
            sb.AppendLine("if backing_m > 0:");
            sb.AppendLine("    bpy.ops.mesh.primitive_cube_add(location=(0.0, 0.0, -backing_m / 2.0))");
            sb.AppendLine("    substrate = bpy.context.active_object");
            sb.AppendLine("    substrate.name = 'Backing'");
            sb.AppendLine("    substrate.dimensions = (width_m, height_m, backing_m)");
            sb.AppendLine("    substrate.data.materials.append(substrate_mat)");
            sb.AppendLine("    substrate.parent = print_root");
            sb.AppendLine();
            sb.AppendLine("if lens_free:");
            sb.AppendLine("    relief = build_lens_mesh(axis_values, width_m, height_m, peak_m, vertical_lenses)");
            sb.AppendLine("    relief.name = 'DirectionalRelief'");
            sb.AppendLine("    relief.data.name = 'DirectionalReliefMesh'");
            sb.AppendLine("    for poly in relief.data.polygons:");
            sb.AppendLine("        poly.use_smooth = False");
            sb.AppendLine("    relief.data.materials.append(print_mat)");
            sb.AppendLine("    apply_planar_uv(relief)");
            sb.AppendLine("    relief['lenticulizer_output_mode'] = 'Lens-Free Relief'");
            sb.AppendLine("    relief['lenticulizer_views'] = view_count");
            sb.AppendLine("    relief.parent = print_root");
            sb.AppendLine("else:");
            sb.AppendLine("    bpy.ops.mesh.primitive_plane_add(location=(0.0, 0.0, 0.00001))");
            sb.AppendLine("    print_plane = bpy.context.active_object");
            sb.AppendLine("    print_plane.name = 'InterlacedImage'");
            sb.AppendLine("    print_plane.scale = (width_m / 2.0, height_m / 2.0, 1.0)");
            sb.AppendLine("    if len(print_plane.data.uv_layers) == 0:");
            sb.AppendLine("        print_plane.data.uv_layers.new(name='UVMap')");
            sb.AppendLine("    print_plane.data.materials.append(print_mat)");
            sb.AppendLine("    print_plane.parent = print_root");
            sb.AppendLine("    lens = build_lens_mesh(axis_values, width_m, height_m, peak_m, vertical_lenses)");
            sb.AppendLine("    lens.data.materials.append(lens_mat)");
            sb.AppendLine("    lens.parent = print_root");
            sb.AppendLine();
            sb.AppendLine("bpy.ops.object.empty_add(type='PLAIN_AXES', location=(0.0, peak_m * 0.45, 0.0))");
            sb.AppendLine("target = bpy.context.active_object");
            sb.AppendLine("target.name = 'ViewTarget'");
            sb.AppendLine("distance_m = max(width_m, height_m) * 1.8 + max(backing_m, peak_m) * 15.0");
            sb.AppendLine("angles = []");
            sb.AppendLine("if view_count <= 1:");
            sb.AppendLine("    angles = [0.0]");
            sb.AppendLine("else:");
            sb.AppendLine("    start = -view_angle_deg / 2.0");
            sb.AppendLine("    step = view_angle_deg / max(1, view_count - 1)");
            sb.AppendLine("    angles = [start + step * i for i in range(view_count)]");
            sb.AppendLine("    fine = [start + (view_angle_deg / 6.0) * i for i in range(7)]");
            sb.AppendLine("    for a in fine:");
            sb.AppendLine("        if all(abs(a - b) > 0.001 for b in angles):");
            sb.AppendLine("            angles.append(a)");
            sb.AppendLine("angles = sorted(angles)");
            sb.AppendLine("center_index = min(range(len(angles)), key=lambda i: abs(angles[i]))");
            sb.AppendLine("for idx, angle in enumerate(angles):");
            sb.AppendLine("    name = f'View_{idx + 1:02d}_{angle:+0.1f}deg'");
            sb.AppendLine("    add_camera(angle, distance_m, target, idx == center_index, name)");
            sb.AppendLine();
            sb.AppendLine("render_dir = os.path.join(base_dir, 'renders')");
            sb.AppendLine("os.makedirs(render_dir, exist_ok=True)");
            sb.AppendLine("scene.render.filepath = os.path.join(render_dir, 'view_center.png')");
            sb.AppendLine("blend_name = 'Lenticulizer_3D_LensFree_Project.blend' if lens_free else 'Lenticulizer_3D_Lenticular_Project.blend'");
            sb.AppendLine("bpy.ops.wm.save_as_mainfile(filepath=os.path.join(base_dir, blend_name))");
            return sb.ToString();
        }

        public static string BuildBlenderReadme(double totalThicknessMm, double baseThicknessMm, double backingMm, double widthMm, double heightMm, bool lensFree)
        {
            var sb = new StringBuilder();
            sb.AppendLine("Blender Simulation Package");
            sb.AppendLine();
            sb.AppendLine("This package builds a Blender Cycles scene that uses:");
            sb.AppendLine("- the interlaced image at exact physical size");
            sb.AppendLine("- the matching 16-bit heightmap");
            sb.AppendLine(backingMm > 0 ? "- a backing block under the print" : "- no separate backing/support block");
            sb.AppendLine(lensFree ? "- a directional relief mesh generated from the depth map, with the color map applied directly to its topology" : "- a clear refractive lens mesh generated from the heightmap");
            sb.AppendLine("- multiple camera angles to evaluate crosstalk and viewing behavior");
            sb.AppendLine();
            sb.AppendLine("Project settings:");
            sb.AppendLine("- Print size: " + widthMm.ToString("0.###", CultureInfo.InvariantCulture) + " x " + heightMm.ToString("0.###", CultureInfo.InvariantCulture) + " mm");
            sb.AppendLine("- UV Thickness: " + totalThicknessMm.ToString("0.###", CultureInfo.InvariantCulture) + " mm");
            sb.AppendLine("- Valley height: " + baseThicknessMm.ToString("0.###", CultureInfo.InvariantCulture) + " mm");
            sb.AppendLine(backingMm > 0 ? "- Backing thickness: " + backingMm.ToString("0.###", CultureInfo.InvariantCulture) + " mm" : "- Backing: disabled");
            sb.AppendLine();
            sb.AppendLine("How to use:");
            sb.AppendLine("1. Extract this ZIP to a normal folder.");
            sb.AppendLine("2. Open Lenticulizer_3D_Template.blend in Blender.");
            sb.AppendLine("3. In Blender's Scripting workspace, open blender_simulation.py from the extracted folder and click Run Script.");
            sb.AppendLine("4. Blender will create and save a Lenticulizer_3D project .blend in the same folder.");
            sb.AppendLine("5. The print is standing upright. Use the Front and side/up/down view cameras to inspect the optical result.");
            sb.AppendLine();
            sb.AppendLine("Notes:");
            sb.AppendLine(lensFree ? "- The color map is UV-mapped directly onto the directional relief topology. No separate lens object is created." : "- The interlaced image is rendered as an emission surface so the lens behavior is easier to evaluate without complex lighting setup.");
            if (!lensFree) sb.AppendLine("- The lens uses a clear refractive material in Cycles.");
            sb.AppendLine("- This is a simulation aid. Real UV prints can still differ because of actual resin behavior and printer accuracy.");
            return sb.ToString();
        }

