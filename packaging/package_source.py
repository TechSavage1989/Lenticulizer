"""Create a clean, reproducible-ish Lenticulizer source archive.

The archive intentionally includes required vendored build assets but excludes build
outputs, VCS metadata, interpreter caches, and validation files generated by test
runs. It also embeds a SHA-256 manifest under docs/ for auditability.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import re
from pathlib import Path
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
program_text=(ROOT/"app/Program.cs").read_text(encoding="utf-8")
match=re.search(r'public const string Version\s*=\s*"([^"]+)"',program_text)
if not match: raise RuntimeError("Could not read Program.Version for source packaging.")
VERSION=match.group(1)
ARCHIVE_ROOT = f"Lenticulizer_v{VERSION}_UpdaterFoundation_Source"

EXCLUDED_DIR_NAMES = {
    ".git", ".github-cache", ".vs", "bin", "obj", "dist", "release",
    "__pycache__", "node_modules",
}
EXCLUDED_SUFFIXES = {".pyc", ".pyo", ".tmp", ".part"}


def is_generated_validation_file(relative: Path) -> bool:
    p = relative.as_posix()
    if not p.startswith("validation/heightmap-fixtures/"):
        return False
    name = relative.name
    return (
        name.startswith("copy_")
        or name.endswith("_copy.tif")
        or name.endswith("_csharp.tif")
    )


def source_files(root: Path = ROOT):
    files=[]
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        relative=path.relative_to(root)
        if any(part in EXCLUDED_DIR_NAMES for part in relative.parts[:-1]):
            continue
        if path.suffix.lower() in EXCLUDED_SUFFIXES:
            continue
        if is_generated_validation_file(relative):
            continue
        files.append((path,relative))
    return files


def digest(path: Path) -> str:
    h=hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda:stream.read(1024*1024),b""):
            h.update(chunk)
    return h.hexdigest()


def build(output: Path):
    subprocess.run([sys.executable, str(ROOT/"scripts/check_root.py")], cwd=ROOT, check=True)
    output=output.resolve()
    output.parent.mkdir(parents=True,exist_ok=True)
    if output.exists(): output.unlink()
    entries=[]
    for path,relative in source_files():
        entries.append({"path":relative.as_posix(),"size":path.stat().st_size,"sha256":digest(path)})
    manifest={
        "schema":1,
        "application":"Lenticulizer",
        "version":VERSION,
        "archive_root":ARCHIVE_ROOT,
        "file_count":len(entries),
        "files":entries,
    }
    with zipfile.ZipFile(output,"w",compression=zipfile.ZIP_DEFLATED,compresslevel=6,allowZip64=True) as archive:
        for path,relative in source_files():
            archive.write(path,f"{ARCHIVE_ROOT}/{relative.as_posix()}")
        archive.writestr(
            f"{ARCHIVE_ROOT}/docs/source-archive-manifest.json",
            json.dumps(manifest,indent=2,sort_keys=True)+"\n",
        )
    archive_hash=digest(output)
    sums=output.with_name(output.stem+"_SHA256.txt")
    sums.write_text(f"{archive_hash}  {output.name}\n",encoding="utf-8")
    print(f"Created {output} ({output.stat().st_size:,} bytes; {len(entries)} source files)")
    print(f"SHA-256: {archive_hash}")
    return archive_hash


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("output",nargs="?",type=Path,default=ROOT.parent/f"{ARCHIVE_ROOT}.zip")
    args=parser.parse_args()
    build(args.output)

if __name__=="__main__": main()
